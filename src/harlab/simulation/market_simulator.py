class MarketSimulator:
    """Deterministic synthetic LOB simulator driven by a seeded ``random.Random``."""

    def __init__(self, config: SimulationConfig | None = None) -> None:
        self.config = config or SimulationConfig()
        self.config.validate()
        self._rng = random.Random(self.config.seed)
        self.book = OrderBook(tick_size=self.config.tick_size)
        self.engine = MatchingEngine(self.book)
        self._order_counter = 0

    def _next_order_id(self, prefix: str = "SIM") -> str:
        self._order_counter += 1
        return f"{prefix}-{self._order_counter:06d}"

    def _seed_initial_book(self) -> None:
        tick = self.config.tick_size
        mid_ticks = int(self.config.initial_mid // tick)
        half_spread = max(1, self.config.base_spread_ticks // 2)
        for lvl in range(self.config.initial_levels):
            bid_ticks = max(1, mid_ticks - half_spread - lvl)
            ask_ticks = mid_ticks + half_spread + lvl
            b_qty = self._rng.randint(self.config.min_qty, self.config.max_qty)
            a_qty = self._rng.randint(self.config.min_qty, self.config.max_qty)
            self.engine.submit_limit_order(
                self._next_order_id("INIT-B"), "buy", bid_ticks * tick, b_qty
            )
            self.engine.submit_limit_order(
                self._next_order_id("INIT-A"), "sell", ask_ticks * tick, a_qty
            )

    def run(self) -> dict[str, Any]:
        """Run the full synthetic simulation and return reproducible series & logs."""
        self._seed_initial_book()
        tick = self.config.tick_size
        reference_ticks = int(self.config.initial_mid // tick)

        series: list[dict[str, Any]] = []
        events: list[dict[str, Any]] = []

        for step in range(1, self.config.steps + 1):
            # Maintain a reference price anchor even if one side briefly empties
            if self.book.best_bid_ticks is not None and self.book.best_ask_ticks is not None:
                reference_ticks = (self.book.best_bid_ticks + self.book.best_ask_ticks) // 2

            u = self._rng.random()
            side: Side = "buy" if self._rng.random() < self.config.buy_bias else "sell"
            qty = self._rng.randint(self.config.min_qty, self.config.max_qty)

            event_record: dict[str, Any] = {
                "step": step,
                "event_type": "",
                "side": side,
                "price": None,
                "quantity": qty,
                "trades_count": 0,
            }

            if u < self.config.cancel_prob and self.book.active_orders():
                active = self.book.active_orders()
                target = self._rng.choice(active)
                self.engine.cancel_order(target.order_id)
                event_record.update(
                    {
                        "event_type": "cancel",
                        "order_id": target.order_id,
                        "side": target.side,
                        "price": float(target.price),
                        "quantity": target.quantity,
                    }
                )
            elif u < self.config.cancel_prob + self.config.marketable_order_prob:
                # Aggressive limit order priced to cross opposite best (if present)
                if side == "buy" and self.book.best_ask_ticks is not None:
                    px_ticks = self.book.best_ask_ticks + self._rng.randint(0, 1)
                elif side == "sell" and self.book.best_bid_ticks is not None:
                    px_ticks = max(1, self.book.best_bid_ticks - self._rng.randint(0, 1))
                else:
                    px_ticks = max(1, reference_ticks)
                oid = self._next_order_id("MKT")
                trades = self.engine.submit_limit_order(oid, side, px_ticks * tick, qty)
                event_record.update(
                    {
                        "event_type": "aggressive_limit",
                        "order_id": oid,
                        "price": float(px_ticks * tick),
                        "trades_count": len(trades),
                        "executed_qty": sum(t.quantity for t in trades),
                    }
                )
            else:
                # Passive resting limit order near the top of the book
                offset = self._rng.randint(1, max(1, self.config.volatility_ticks))
                if side == "buy":
                    anchor = self.book.best_ask_ticks or (reference_ticks + 1)
                    px_ticks = max(1, anchor - offset)
                else:
                    anchor = self.book.best_bid_ticks or max(1, reference_ticks - 1)
                    px_ticks = anchor + offset
                oid = self._next_order_id("LMT")
                trades = self.engine.submit_limit_order(oid, side, px_ticks * tick, qty)
                event_record.update(
                    {
                        "event_type": "passive_limit",
                        "order_id": oid,
                        "price": float(px_ticks * tick),
                        "trades_count": len(trades),
                        "executed_qty": sum(t.quantity for t in trades),
                    }
                )

            events.append(event_record)

            mid = mid_price(self.book)
            mpx = microprice(self.book)
            spr = self.book.spread
            series.append(
                {
                    "step": step,
                    "best_bid": float(self.book.best_bid) if self.book.best_bid is not None else None,
                    "best_ask": float(self.book.best_ask) if self.book.best_ask is not None else None,
                    "mid_price": float(mid) if mid is not None else None,
                    "microprice": float(mpx) if mpx is not None else None,
                    "spread": float(spr) if spr is not None else None,
                    "imbalance_l1": order_imbalance(self.book, levels=1),
                    "imbalance_l5": order_imbalance(self.book, levels=5),
                    "bid_depth_l1": bid_depth(self.book, levels=1),
                    "ask_depth_l1": ask_depth(self.book, levels=1),
                    "bid_depth_total": bid_depth(self.book, levels=None),
                    "ask_depth_total": ask_depth(self.book, levels=None),
                    "cumulative_volume": self.engine.total_executed_quantity,
                    "last_trade_price": float(self.engine.trades[-1].price) if self.engine.trades else None,
                }
            )

        cfg_dict = asdict(self.config)
        cfg_dict["initial_mid"] = float(self.config.initial_mid)
        cfg_dict["tick_size"] = float(self.config.tick_size)

        return {
            "data_origin": "SYNTHETIC",
            "is_synthetic": True,
            "disclaimer": (
                "Synthetic simulation output for controlled microstructure research only. "
                "Not live market data."
            ),
            "config": cfg_dict,
            "series": series,
            "events": events[-100:],
            "total_events": len(events),
            "trades": [
                {
                    "trade_id": t.trade_id,
                    "buy_order_id": t.buy_order_id,
                    "sell_order_id": t.sell_order_id,
                    "price": float(t.price),
                    "quantity": t.quantity,
                    "aggressor_side": t.aggressor_side,
                    "timestamp": t.timestamp,
                }
                for t in self.engine.trades[-100:]
            ],
            "final_snapshot": {
                "bids": [[float(p), q] for p, q in self.book.depth("buy", 10)],
                "asks": [[float(p), q] for p, q in self.book.depth("sell", 10)],
            },
            "execution_stats": execution_statistics(self.engine),
        }
