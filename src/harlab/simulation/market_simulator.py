@dataclass
class SimulationConfig:
    """Configuration for a reproducible synthetic LOB simulation."""

    seed: int = 42
    steps: int = 200
    initial_mid: Decimal = Decimal("100.00")
    tick_size: Decimal = DEFAULT_TICK_SIZE
    initial_levels: int = 5
    base_spread_ticks: int = 2
    limit_order_prob: float = 0.65
    marketable_order_prob: float = 0.20
    cancel_prob: float = 0.15
    buy_bias: float = 0.50
    volatility_ticks: int = 3
    min_qty: int = 10
    max_qty: int = 200
    scenario_name: str = "baseline_symmetric"

    def validate(self) -> None:
        if self.steps < 1 or self.steps > 20000:
            raise ValueError("steps must be between 1 and 20000")
        if self.initial_mid <= 0:
            raise ValueError("initial_mid must be positive")
        if self.tick_size <= 0:
            raise ValueError("tick_size must be positive")
        if self.initial_levels < 1 or self.initial_levels > 25:
            raise ValueError("initial_levels must be between 1 and 25")
        if self.base_spread_ticks < 1:
            raise ValueError("base_spread_ticks must be >= 1")
        if not (0.0 <= self.buy_bias <= 1.0):
            raise ValueError("buy_bias must be in [0, 1]")
        prob_sum = self.limit_order_prob + self.marketable_order_prob + self.cancel_prob
        if abs(prob_sum - 1.0) > 1e-6:
            raise ValueError(
                f"event probabilities must sum to 1.0 (got {prob_sum:.4f})"
            )
        if self.min_qty < 1 or self.max_qty < self.min_qty:
            raise ValueError("invalid min_qty/max_qty bounds")


